def generate_social_story(db: Session, request: schemas.StoryGenerateRequest) -> schemas.StoryCreate:
    # 1. Retrieve or define situation info
    situation_title = "New Situation"
    situation_desc = ""
    
    if request.situation_id:
        db_situation = db.query(models.Situation).filter(models.Situation.id == request.situation_id).first()
        if db_situation:
            situation_title = db_situation.title
            situation_desc = db_situation.description
            
    if request.custom_situation_text:
        # If both are provided, let's use the custom text as description
        if not request.situation_id:
            situation_title = "Custom Situation"
        situation_desc = request.custom_situation_text

    if request.custom_title:
        situation_title = request.custom_title

    # 2. Check if Gemini API key is missing or set to placeholder
    api_key = os.getenv("GEMINI_API_KEY")
    is_missing = not api_key or api_key == "YOUR_API_KEY_HERE" or api_key.strip() == ""

    if is_missing:
        logger.warning("[AI Service] GEMINI_API_KEY is not configured or set to placeholder. Using fallback/mock generation mode.")
        return _generate_mock_social_story(db, request, source="fallback")

    # 3. Live Gemini API Generation
    child_name = request.child_name
    child_age = request.child_age
    key_details = request.key_details

    prompt_details = ""
    if child_name:
        prompt_details += f"- Personalize the story by introducing the child at the beginning (e.g., 'My name is {child_name}.').\n"
    if child_age:
        prompt_details += f"- The child's age is {child_age}. Ensure the vocabulary, sentence length, and reading level are highly appropriate for a {child_age}-year-old child.\n"
    if key_details:
        prompt_details += f"- Incorporate the child's special details, triggers, interests, and calming tools: '{key_details}'. Weave them naturally and reassuringly into the story narrative as gentle coping options (e.g., 'I can choose to use/think about...' or 'It helps me to...') rather than commands.\n"

    prompt = f"""
You are a friendly educational expert specializing in writing Carol Gray-inspired Social Stories for young children.
Write a personalized, reassuring, and highly predictable Social Story based on these details:
- Story Title Topic: {situation_title}
- Story Scenario: {situation_desc}
- Child's Name: {child_name or "Not specified"}
- Child's Age: {child_age or "Not specified"}
- Child's Details / Triggers / Interests / Calming Tools: {key_details or "None"}

Follow these Carol Gray Social Story Guidelines:
1. First-Person Perspective: The story MUST be written entirely from the child's point of view using first-person pronouns: "I", "my", "me", "we", "our". Do NOT write in the second or third person. Even if the child's name is provided, refer to yourself as "I" or "me" (e.g., "My name is {child_name or 'I'}. Today I am going to...").
2. Simple, Literal, & Reassuring Language: Keep sentences short, concrete, and literal. Avoid all abstract metaphors, idioms, figures of speech, or sarcasm. Ensure the tone is calm, warm, and highly predictable.
3. Descriptive & Perspective Sentences:
   - Descriptive sentences: Describe objectively what is happening, where it is, and who is there (e.g., "The dentist clinic has a big chair. The dentist works there.").
   - Perspective sentences: Describe the thoughts, feelings, or helpful motivations of other people in a reassuring way (e.g., "The dentist wants to help my teeth stay healthy. This makes them happy.").
4. Gentle Coping Options, NOT Commands: Suggest positive, manageable actions or coping tools the child can take (e.g., raising a hand, taking deep breaths, holding a favorite object). Frame these actions as gentle choices/options (e.g., "I can choose to...", "I can try to...") rather than absolute commands or requirements (do NOT use "I must", "I should", "I have to").
5. Avoid Clinical/Diagnosis Language: Do NOT mention any diagnostic terms, conditions, or labels (such as "autism", "neurodivergence", "ADHD", "sensory overload"). Keep the focus purely on the child's personal experience of the situation.
6. Avoid Promising Outcomes: Do NOT guarantee or promise perfect outcomes (e.g., do NOT write "It will never hurt" or "I will be perfectly happy"). Instead, focus on predictability and support (e.g., "My helpers will be there to support me," "This helps me know what to expect.").
7. Length & Structure:
   - Provide exactly 5 to 7 pages.
   - Each page must contain exactly 2 to 3 short, simple sentences.

You must return valid JSON matching this schema:
{{
  "title": "A calm, child-appropriate title for the story",
  "pages": [
    {{
      "page_number": 1,
      "text": "2-3 short, simple first-person story sentences appropriate for a child.",
      "visual_prompt": "A description of a friendly, calm, flat-vector Scandinavian style illustration matching this page"
    }}
  ]
}}
"""

    try:
        logger.info("[AI Service] Requesting social story generation from Gemini API...")
        # Initialize the client with the api key
        client = genai.Client(api_key=api_key)
        
        response = client.models.generate_content(
            model='gemini-2.5-flash',
            contents=prompt,
            config=types.GenerateContentConfig(
                response_mime_type="application/json",
                response_schema=StoryResponseSchema,
                temperature=0.2
            )
        )
        
        if not response.text:
            raise RuntimeError("Received empty response from Gemini API.")
            
        story_data = json.loads(response.text)
        title = clean_story_title(story_data.get("title") or situation_title, request, is_gemini_generated=True)
        pages = story_data.get("pages", [])
        
        story_pages = [
            schemas.StoryPage(
                page_number=page.get("page_number", idx + 1),
                text=page.get("text", ""),
                visual_prompt=page.get("visual_prompt", "")
            )
            for idx, page in enumerate(pages)
        ]
        
        if not story_pages:
            raise RuntimeError("Gemini generated a story with no pages.")
            
        logger.info(f"[AI Service] Successfully generated social story '{title}' from Gemini API.")
        return schemas.StoryCreate(
            title=title,
            situation_id=request.situation_id,
            generation_source="gemini",
            content=story_pages
        )
        
    except Exception as e:
        # Fall back to mock story generation on ANY live failure or parse error
        logger.error(f"[AI Service] Gemini AI generation failed: {e}. Falling back to mock generation mode.")
        return _generate_mock_social_story(db, request, source="fallback")

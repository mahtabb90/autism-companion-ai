# Manual dotenv loader to read environment variables from a .env file securely
def load_dotenv():
    # Look for .env in current working directory, backend/ and project root parent directories
    for folder in [
        pathlib.Path.cwd(), 
        pathlib.Path(__file__).parent.parent.parent, 
        pathlib.Path(__file__).parent.parent.parent.parent
    ]:
        for filename in [".env", "backend/.env"]:
            path = folder / filename
            if path.exists():
                try:
                    with open(path, "r", encoding="utf-8") as f:
                        for line in f:
                            line = line.strip()
                            if line and not line.startswith("#") and "=" in line:
                                key, val = line.split("=", 1)
                                os.environ[key.strip()] = val.strip().strip('"').strip("'")
                except Exception as e:
                    print(f"Error loading env file {path}: {e}")

load_dotenv()

# Pydantic schema for Gemini structured JSON response
class StoryPageResponse(BaseModel):
    page_number: int
    text: str
    visual_prompt: str

class StoryResponseSchema(BaseModel):
    title: str
    pages: List[StoryPageResponse]


def clean_story_title(title: str, request: schemas.StoryGenerateRequest, is_gemini_generated: bool = False) -> str:
    if not title:
        return ""
    
    title = title.strip()
    
    if request.custom_title:
        return request.custom_title

    # If it is generated by Gemini, keep it exactly as-is!
    if is_gemini_generated:
        return title

    # If title starts with "Story about ", check if we should keep the prefix
    if title.lower().startswith("story about "):
        topic = title[12:].strip()
        standard_topics = {
            "going to the dentist",
            "getting a haircut",
            "sharing toys at school",
            "sharing toys with friends",
            "custom situation",
            "new situation"
        }
        if topic.lower() in standard_topics:
            return title
        return topic

    # If it does not start with "Story about ", check if we should prepend it
    # We only prepend "Story about " if the title is one of the generic/standard ones
    standard_topics = {
        "going to the dentist",
        "getting a haircut",
        "sharing toys at school",
        "sharing toys with friends",
        "custom situation",
        "new situation"
    }
    if title.lower() in standard_topics:
        return f"Story about {title}"
        
    return title


